alter table public.messages replica identity full;

grant select on public.messages to authenticated;

drop policy if exists "Our Space members can read messages" on public.messages;
drop policy if exists "Our Space message access" on public.messages;

create policy "Our Space members can read messages"
on public.messages
for select
to authenticated
using (
  exists (
    select 1
    from public.space_members sm
    where sm.space_id = messages.space_id
      and sm.user_id = (select auth.uid())
  )
  and (
    deleted_at is null
    or (select auth.uid()) = '28c4929b-ed2c-4eec-a850-88d50bce8e91'::uuid
  )
);

grant insert on public.messages to authenticated;

drop policy if exists "Our Space members can send messages" on public.messages;
drop policy if exists "Our Space message insert" on public.messages;

create policy "Our Space members can send messages"
on public.messages
for insert
to authenticated
with check (
  sender_id = (select auth.uid())
  and exists (
    select 1
    from public.space_members sm
    where sm.space_id = messages.space_id
      and sm.user_id = (select auth.uid())
  )
);

-- ============================================================
-- SEEN
-- ============================================================

drop function if exists public.mark_message_seen(bigint);

create function public.mark_message_seen(p_message_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  changed boolean := false;
begin
  update public.messages m
  set seen_at = coalesce(m.seen_at, now())
  where m.id = p_message_id
    and m.sender_id <> (select auth.uid())
    and exists (
      select 1
      from public.space_members sm
      where sm.space_id = m.space_id
        and sm.user_id = (select auth.uid())
    );

  changed := found;
  return changed;
end;
$$;

revoke all on function public.mark_message_seen(bigint) from public, anon;
grant execute on function public.mark_message_seen(bigint) to authenticated;

-- ============================================================
-- DELETE FOR EVERYONE
-- ============================================================

drop function if exists public.delete_message_for_everyone(bigint);

create function public.delete_message_for_everyone(p_message_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  changed boolean := false;
begin
  update public.messages m
  set
    deleted_at = coalesce(m.deleted_at, now()),
    deleted_by = (select auth.uid())
  where m.id = p_message_id
    and m.sender_id = (select auth.uid())
    and m.deleted_at is null
    and exists (
      select 1
      from public.space_members sm
      where sm.space_id = m.space_id
        and sm.user_id = (select auth.uid())
    );

  changed := found;
  return changed;
end;
$$;

revoke all on function public.delete_message_for_everyone(bigint) from public, anon;
grant execute on function public.delete_message_for_everyone(bigint) to authenticated;
    
-- ============================================================
-- SECURE DELETION BROADCAST
-- ============================================================
-- Deleted rows remain hidden from Salma by the messages SELECT policy above.
-- Realtime Postgres Changes therefore cannot be relied on for the hidden row.
-- Broadcast only the message id + space id, never the deleted content.

create or replace function public.broadcast_message_deleted()
returns trigger
language plpgsql
security definer
set search_path = ''
as $
begin
  if old.deleted_at is null and new.deleted_at is not null then
    perform realtime.send(
      jsonb_build_object(
        'message_id', new.id,
        'space_id', new.space_id
      ),
      'message_deleted',
      'our-space-chat-' || new.space_id::text,
      true
    );
  end if;

  return new;
end;
$;

revoke all on function public.broadcast_message_deleted() from public, anon, authenticated;

drop trigger if exists messages_deleted_broadcast on public.messages;

create trigger messages_deleted_broadcast
after update of deleted_at on public.messages
for each row
execute function public.broadcast_message_deleted();

drop policy if exists "Our Space members can receive deletion broadcasts"
on realtime.messages;

create policy "Our Space members can receive deletion broadcasts"
on realtime.messages
for select
to authenticated
using (
  extension = 'broadcast'
  and exists (
    select 1
    from public.space_members sm
    where sm.user_id = (select auth.uid())
      and ('our-space-chat-' || sm.space_id::text) = (select realtime.topic())
  )
);

